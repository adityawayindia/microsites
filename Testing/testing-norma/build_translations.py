"""Build this preview's browser catalogs with the shared Google Cloud NMT generator.

Run with the workspace Python environment and GOOGLE_CLOUD_PROJECT set, or use
--drafts PATH to package a completed translation run without calling Google.
Translation provider: https://cloud.google.com/translate
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory


SITE = Path(__file__).resolve().parent
GENERATOR = SITE.parent / "Google NMT" / "translate.py"


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def package(drafts):
    labels = read(SITE / "locales/en.json")
    doctor = read(SITE / "content/doctor.en.json")
    facts = read(SITE / "content/doctor_facts.json")
    spellings = read(SITE / "content/doctor_display.json")
    catalogs = {}
    for lang in ("en", "hi", "or", "bn"):
        ui = labels if lang == "en" else read(drafts / "locales" / f"{lang}.json")
        profile = doctor if lang == "en" else read(drafts / "content" / f"doctor.{lang}.json")
        for source, translated in ((labels, ui), (doctor, profile)):
            if source.keys() != translated.keys() or any(source[g].keys() != translated[g].keys() for g in source):
                raise ValueError(f"Incomplete {lang} catalog: regenerate the drafts for this site.")
        catalog = {group: dict(fields) for group, fields in ui.items()}
        for group, fields in profile.items():
            catalog.setdefault(group, {}).update(fields)
        catalog["display_facts"] = {**facts, **spellings.get(lang, {})}
        catalog["display_facts"]["clinic_address"] = ui["contact_us"]["street_address_not_listed"]
        catalogs[lang] = catalog

    for lang, catalog in catalogs.items():
        payload = json.dumps(catalog, ensure_ascii=False, indent=2)
        output = SITE / "locales" / f"{lang}.js"
        output.write_text(f"// Generated by build_translations.py\nwindow.micrositeLanguage.catalogs.{lang} = {payload};\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--drafts", type=Path, help="Package an existing Google NMT draft directory.")
    args = parser.parse_args()
    if args.drafts:
        package(args.drafts)
    else:
        with TemporaryDirectory() as directory:
            subprocess.run([
                sys.executable, str(GENERATOR), "--template", str(SITE / "locales/en.json"),
                "--doctor", str(SITE / "content/doctor.en.json"), "--output", directory,
            ], check=True)
            package(Path(directory))
